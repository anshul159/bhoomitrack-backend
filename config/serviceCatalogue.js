// The service catalogue (BhoomiTrack Services, plan §3 and §6.1).
//
// The app holds no list of services of its own: it renders doors, rows, detail
// screens and request forms from what GET /api/services/catalogue returns. So a
// new service, a changed price hint or a service switched off is a backend deploy,
// not a Play release.
//
// Rules, enforced by tests/servicecatalogue.test.js:
//   - six doors, fixed; a seventh is never added (plan §5.1 rule 2);
//   - at most eight visible rows behind a door, and at most five fields in a form;
//   - an entry that is `regulated` and `live` must name its licensed `partner`
//     (plan §4: nothing regulated goes live without one);
//   - every insurance and credit entry is 'interest' until that partner is signed.
//
// status: 'live'     — the owner can send a request; the desk fulfils it.
//         'interest' — "Tell me when this is available": the tap is recorded as
//                      demand and nothing else happens.
//         'hidden'   — not sent to the app at all.
//
// Words (plan §5.7): plain names, the formal name underneath; nothing is called
// free if somebody pays us for it; every entry says who does the work and what it
// costs before the owner taps Request.


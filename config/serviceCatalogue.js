/**
 * The doors and services this organisation may see.
 * @param {object} profile  Organization.profile, for state-specific services
 */
function catalogueFor(profile = {}) {
  const state = profile?.state || null;
  const visible = SERVICES.filter((s) => s.status !== 'hidden' && (!s.states || (state && s.states.includes(state))));
  return {
    doors: DOORS.map((d) => ({ ...d, service_count: visible.filter((s) => s.door === d.id).length })),
    services: visible.map(presentService),
  };
}

/** What the app receives: everything it renders, nothing it does not need. */
function presentService(s) {
  return {
    id: s.id,
    door: s.door,
    title: s.title,
    formal_name: s.formal_name || null,
    line: s.line,
    status: s.status,
    regulated: s.regulated,
    price_hint: s.price_hint,
    cost: s.cost,
    who: s.partner ? `${s.partner.name} (licence ${s.partner.licence_no})` : s.who,
    partner: s.partner || null,
    about: s.about,
    asks_profile: s.asks_profile || [],
    needs: s.needs,
    shares: s.shares,
    fills_slot: s.fills_slot,
  };
}

module.exports = { DOORS, SERVICES, FIELD_TYPES, getService, catalogueFor, presentService };
